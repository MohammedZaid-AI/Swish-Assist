-- Swish Assist schema for Supabase Postgres.
-- Run once in the Supabase SQL editor. The SQLite fallback creates the same tables automatically.

create table if not exists menu_items (
  id text primary key,
  name text not null,
  category text,
  price_inr integer not null,
  is_veg boolean default false,
  description text,
  image_url text,
  typical_look text
);

create table if not exists users (
  id text primary key,
  phone text unique,
  name text,
  language_pref text check (language_pref in ('en', 'hi_en', 'kn')) default 'en',
  created_at timestamptz default now()
);

create table if not exists orders (
  id text primary key,
  user_id text references users(id) on delete cascade,
  items jsonb not null,            -- [{menu_item_id, name, qty, price}]
  subtotal integer,
  discount integer default 0,
  total integer,
  coupon_code text,
  status text check (status in ('placed','preparing','packed','out_for_delivery','delivered','cancelled')),
  placed_at timestamptz,
  preparing_at timestamptz,
  packed_at timestamptz,
  out_for_delivery_at timestamptz,
  delivered_at timestamptz,
  eta_minutes integer,
  delay_reason text,
  kitchen_name text,
  kitchen_distance_km real,
  rider_name text
);
create index if not exists orders_user_idx on orders(user_id, placed_at desc);

create table if not exists coupons (
  code text primary key,
  description text,
  type text check (type in ('flat','percent')),
  value integer,
  min_order_inr integer default 0,
  max_discount_inr integer,
  valid_from timestamptz,
  valid_to timestamptz,
  first_order_only boolean default false,
  max_uses_per_user integer,
  allowed_days jsonb,              -- e.g. [0,1,2,3,4] (Mon=0, IST)
  allowed_hours jsonb,             -- e.g. [12, 15] (IST, end exclusive)
  active boolean default true
);

create table if not exists coupon_uses (
  id text primary key,
  user_id text references users(id) on delete cascade,
  coupon_code text references coupons(code) on delete cascade,
  order_id text,
  used_at timestamptz
);

create table if not exists complaints (
  id text primary key,
  order_id text,
  user_id text references users(id) on delete cascade,
  type text check (type in ('missing_item','wrong_item','quality','late','other')),
  user_message text,
  image_url text,
  image_hash text,
  vision_model text,
  vision_latency_ms integer,
  vision_result jsonb,
  fraud_flags jsonb,
  decision text check (decision in ('auto_refund','auto_replace','escalated','rejected','no_issue_found')),
  refund_amount_inr integer default 0,
  decision_reason text,
  human_decision text,
  created_at timestamptz default now(),
  resolved_at timestamptz,
  resolution_seconds real
);
create index if not exists complaints_created_idx on complaints(created_at desc);

create table if not exists conversations (
  id bigint generated by default as identity primary key,
  user_id text references users(id) on delete cascade,
  channel text check (channel in ('whatsapp','web')),
  role text,
  content text,
  tool_name text,
  tool_payload jsonb,
  created_at timestamptz default now()
);
create index if not exists conversations_user_idx on conversations(user_id, created_at desc);
